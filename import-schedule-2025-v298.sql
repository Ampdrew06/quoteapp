-- Use the same job-number locks as the live Schedule editor.
SELECT pg_advisory_xact_lock(hashtextextended(job_key,0))
FROM pg_temp.timberlite_import_2025_stage ORDER BY job_key;
WITH assessed AS MATERIALIZED (
 SELECT s.*,
  CASE WHEN EXISTS (SELECT 1 FROM public.timberlite_schedule_entries e WHERE e.id=s.id)
       THEN 'already imported'
       WHEN EXISTS (
        SELECT 1 FROM public.timberlite_schedule_entries e LEFT JOIN public.quotes q ON q.id=e.quote_id
        WHERE lower(btrim(e.entry_json->>'jobNumber'))=s.job_key
          AND (e.quote_id IS NULL OR (q.status='converted_to_job' AND q.schedule_included IS TRUE))
       ) OR EXISTS (
        SELECT 1 FROM public.quotes q WHERE q.status='converted_to_job' AND q.schedule_included IS TRUE
          AND lower(btrim(q.job_number::text))=s.job_key
       ) THEN 'existing job number'
       ELSE 'ready' END AS outcome
 FROM pg_temp.timberlite_import_2025_stage s
), inserted AS (
 INSERT INTO public.timberlite_schedule_entries(id,entry_json)
 SELECT id,entry_json FROM assessed WHERE outcome='ready' ORDER BY job_key
 ON CONFLICT (id) DO NOTHING
 RETURNING id,entry_json
)
SELECT (SELECT count(*) FROM inserted) AS imported,
       (SELECT count(*) FROM inserted WHERE entry_json->>'status'='On Hold') AS imported_to_review,
       (SELECT coalesce(round(sum((entry_json->>'netSell')::numeric),2),0) FROM inserted
         WHERE entry_json->>'status'<>'On Hold') AS imported_net_sales,
       count(*) FILTER (WHERE outcome='already imported') AS already_imported,
       coalesce(string_agg(entry_json->>'jobNumber', ', ' ORDER BY job_key)
         FILTER (WHERE outcome='existing job number'), '') AS existing_job_numbers_skipped
FROM assessed;
COMMIT;
